"""Generate the shared closed sticker catalogue; no arbitrary image URLs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
catalog = json.loads((ROOT / 'shared/stickers/classic.json').read_text(encoding='utf-8'))
target = ROOT / 'packages/local_host/lib/src/chat_stickers.g.dart'
lines = ['// Generated by tools/stickers/sync_catalog.py',
    'class ChatSticker {', '  const ChatSticker(this.id, this.role, this.emotion);',
    '  final String id, role, emotion;',
    "  String get asset => 'assets/stickers/classic/$id.png';",
    "  String get label => '$role · $emotion';", '}', '',
    'const chatStickers = <ChatSticker>[']
for item in catalog:
    lines.append('  ChatSticker(' + ', '.join(json.dumps(item[k], ensure_ascii=False) for k in ['id', 'role', 'emotion']) + '),')
lines.extend(['];', '',
    'ChatSticker? chatStickerById(String id) => chatStickers.where((s) => s.id == id).firstOrNull;',
    "String stickerMessage(ChatSticker sticker) => '[[sticker:${sticker.id}]]';",
    'ChatSticker? stickerFromMessage(String text) {',
    r"  final match = RegExp(r'^\[\[sticker:([a-z0-9_]+)\]\]$').firstMatch(text.trim());",
    '  return match == null ? null : chatStickerById(match.group(1)!);', '}', '',
    'void validateStickerMessage(String text) {',
    "  if (text.trim().startsWith('[[sticker:') && stickerFromMessage(text) == null) {",
    "    throw ArgumentError('Sticker inconnu ou indisponible.');", '  }', '}', ''])
target.write_text('\n'.join(lines), encoding='utf-8')
print(str(len(catalog)) + ' stickers synchronized.')
