"""Keep displayed MDJ prompts and generated speech texts identical."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
lines = json.loads((ROOT / 'tools/audio/narration_lines.json').read_text(encoding='utf-8'))
target = ROOT / 'packages/local_host/lib/src/narration_lines.g.dart'
target.write_text('// Generated by tools/audio/sync_narration.py\n'
    'const mdjNarrationLines = <String, String>{\n' + ''.join(
    '  ' + json.dumps(key, ensure_ascii=False) + ': ' + json.dumps(text, ensure_ascii=False) + ',\n'
    for key, text in lines.items()) + '};\n', encoding='utf-8')
print('Shared MDJ texts synchronized.')

labels = {
    'sisters': 'Deux Sœurs', 'mayor_election': 'Élection du Maire', 'mayor_succession': 'Succession du Maire',
    'role_reveal': 'Découverte du rôle', 'sleep': 'Le village s’endort',
    'seer': 'Voyante', 'wolves': 'Loups-Garous', 'witch': 'Sorcière',
    'metamorph': 'Métamorphe', 'cupid': 'Cupidon', 'guardian': 'Salvateur',
    'alpha': 'Grand Méchant Loup', 'infection': 'Père des Loups', 'white_wolf': 'Loup Blanc',
    'piper': 'Joueur de Flûte', 'scapegoat': 'Bouc émissaire', 'dawn': 'Lever du jour',
    'hunter': 'Dernier tir du Chasseur', 'day': 'Débat', 'voting': 'Vote', 'vote_result': 'Résultat du vote',
    'villager': 'Villageois', 'villager_female': 'Villageoise', 'little_girl': 'Petite Fille',
    'elder': 'Ancien', 'wolf_father': 'Père des Loups', 'idiot': 'Idiot du Village',
    'angel': 'Ange', 'werewolf': 'Loup-Garou', 'alpha_wolf': 'Grand Méchant Loup',
    'village': 'Victoire du Village', 'draw': 'Partie nulle', 'lovers': 'Amoureux',
}
catalog = ['# Textes exacts des voix OFF', '',
    'Les annonces du MDJ utilisent le même texte dans les dix profils. '
    'Le profil et le mode automatique sont choisis par le MDJ pour le salon.', '',
    '## Appels et rendormissements du MDJ', '', '| Moment | Texte |', '| --- | --- |']
for cue, line in lines.items():
    label = ('Rendormissement : ' + labels[cue[6:]]) if cue.startswith('close_') else labels[cue]
    catalog.append('| ' + label + ' | « ' + line + ' » |')
info = json.loads((ROOT / 'tools/audio/neural_profiles.json').read_text(encoding='utf-8'))
profiles = {p['id']: p['label'] for p in info['profiles']}
for title, prefix in [('Dernières paroles des cartes', 'death_'), ('Annonces de victoire', 'ended_'),
                      ('Répliques spéciales', None)]:
    catalog.extend(['', '## ' + title, '', '| Événement | Voix | Texte |', '| --- | --- | --- |'])
    for profile, cues in info['extra_lines'].items():
        for cue, line in cues.items():
            if prefix and not cue.startswith(prefix): continue
            if prefix is None and cue.startswith(('death_', 'ended_')): continue
            key = cue[len(prefix):] if prefix else cue
            label = labels.get(key, {'elder_curse': 'Malédiction de l’Ancien', 'witch_potion': 'Potion confirmée'}.get(key, key))
            catalog.append('| ' + label + ' | ' + profiles[profile] + ' | « ' + line + ' » |')
catalog.extend(['', 'La malédiction nécessite la perte réelle des pouvoirs du Village. '
    'Les dernières paroles identifiantes ne sont jouées que pour un rôle révélé publiquement.', '',
    'En local, le MDJ diffuse les sons sur son appareil. En ligne, chaque appareil '
    'utilise le profil du salon et respecte ses volumes et son silence général.', ''])
(ROOT / 'docs/textes-voix-off.md').write_text('\n'.join(catalog), encoding='utf-8')
