"""Build additional role fiches with their implemented gameplay status."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def main():
    data = json.loads((ROOT / 'docs/cards/classic_expansion.json').read_text(encoding='utf-8'))
    roles = data['roles']
    if len(roles) != 13 or len({r['id'] for r in roles}) != 13:
        raise ValueError('Expected thirteen distinct additional cards')
    lines = ["// Generated by tools/cards/build_classic_catalog.py.",
             "part of 'classic_role.dart';", "", "const additionalClassicRoles = ["]
    for role in roles:
        lines.append('  ClassicRole(')
        for key in ('id', 'name', 'camp', 'phase', 'summary', 'details'):
            lines.append('    ' + json.dumps(role[key], ensure_ascii=False) + ',')
        lines.extend(["    implemented: " + str(role.get('implemented', False)).lower() + ",", "    assetExtension: 'png',", '  ),'])
    lines.extend(['];', ''])
    target = ROOT / 'apps/mordeviel/lib/cards/classic_role_catalog.g.dart'
    target.write_text('\n'.join(lines), encoding='utf-8')
    print('Thirteen additional classic role fiches generated.')

if __name__ == '__main__':
    main()
