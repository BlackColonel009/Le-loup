"""Extract Intense house silhouettes as vector metadata; source PNGs are unchanged."""
from collections import defaultdict
from itertools import pairwise
from math import hypot
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def simplify(points, epsilon=.7):
    if len(points) < 3:
        return points
    ax, ay = points[0]
    bx, by = points[-1]
    length = hypot(bx - ax, by - ay)
    distances = [abs((bx - ax) * (ay - y) - (ax - x) * (by - ay)) / length
                 if length else hypot(x - ax, y - ay) for x, y in points]
    index = max(range(len(points)), key=distances.__getitem__)
    if distances[index] <= epsilon:
        return [points[0], points[-1]]
    return simplify(points[:index + 1], epsilon)[:-1] + simplify(points[index:], epsilon)


def contour(path):
    with Image.open(path) as image:
        alpha = image.getchannel('A')
        bounds = alpha.point(lambda a: 255 if a > 8 else 0).getbbox()
        alpha = alpha.crop(bounds).resize((128, 128), Image.Resampling.LANCZOS)
    pixels = {(x, y) for y in range(128) for x in range(128) if alpha.getpixel((x, y)) > 64}
    edges = defaultdict(list)
    for x, y in pixels:
        for neighbor, start, end in [
            ((x, y - 1), (x, y), (x + 1, y)),
            ((x + 1, y), (x + 1, y), (x + 1, y + 1)),
            ((x, y + 1), (x + 1, y + 1), (x, y + 1)),
            ((x - 1, y), (x, y + 1), (x, y)),
        ]:
            if neighbor not in pixels:
                edges[start].append(end)
    loops = []
    while edges:
        start = min(edges)
        points, current = [start], start
        while current in edges:
            following = edges[current].pop()
            if not edges[current]:
                del edges[current]
            points.append(following)
            current = following
            if current == start:
                break
        if points[-1] == start:
            loops.append(points)
    def area(points):
        return abs(sum(ax * by - bx * ay for (ax, ay), (bx, by) in pairwise(points)))
    return simplify(max(loops, key=area))


def main():
    lines = [
        '// Generated by tools/sync_house_contours.py; original PNGs are unchanged.',
        "import 'package:flutter/widgets.dart';",
        'const intenseHouseContours = <String, List<Offset>>{',
    ]
    for state in ['day', 'night', 'eliminated']:
        points = contour(ROOT / f'apps/mordeviel/assets/village/intense/house_{state}.png')
        lines.append(f"  '{state}': [")
        lines.extend(f'    Offset({x / 128:.5f}, {y / 128:.5f}),' for x, y in points[:-1])
        lines.append('  ],')
    lines.append('};')
    output = ROOT / 'apps/mordeviel/lib/village/intense_house_contours.g.dart'
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Contours Intense générés, sans modifier les PNG.')


if __name__ == '__main__':
    main()
