"""Generate tiny bundled metadata; portrait artwork stays in server packs."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
items = json.loads((root / 'shared/avatars/catalog.json').read_text(encoding='utf-8'))['avatars']
target = root / 'apps/mordeviel/lib/profile/avatar_catalog.g.dart'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('// Generated by tools/content/sync_avatars.py\n'
                  'const avatarCatalog = <Map<String, Object>>[\n' +
                  ',\n'.join(json.dumps({k: v for k, v in a.items() if k not in {'source', 'source_root'}}, ensure_ascii=False) for a in items)
                  + '\n];\n', encoding='utf-8')
borders = json.loads((root / 'shared/avatars/borders.json').read_text(encoding='utf-8'))['borders']
(target.parent / 'border_catalog.g.dart').write_text(
    '// Generated by tools/content/sync_avatars.py\nconst avatarBorderCatalog = <Map<String, Object>>[\n'
    + ',\n'.join(json.dumps(b, ensure_ascii=False) for b in borders) + '\n];\n', encoding='utf-8')
print(f'{len(items)} portraits et {len(borders)} bordures décrits, sans image ajoutée à l’application.')
