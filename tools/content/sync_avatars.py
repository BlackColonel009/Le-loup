"""Generate tiny bundled metadata; portrait artwork stays in server packs."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
items = json.loads((root / 'shared/avatars/catalog.json').read_text(encoding='utf-8'))['avatars']
target = root / 'apps/mordeviel/lib/profile/avatar_catalog.g.dart'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('// Generated by tools/content/sync_avatars.py\n'
                  'const avatarCatalog = <Map<String, Object>>[\n' +
                  ',\n'.join(json.dumps({k: v for k, v in a.items() if k != 'source'}, ensure_ascii=False) for a in items)
                  + '\n];\n', encoding='utf-8')
print('20 portraits décrits, sans image ajoutée à l’application.')
